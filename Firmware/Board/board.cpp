void CanFilter_Init(CAN_HandleTypeDef *hcan)
{
    CAN_FilterTypeDef canfilter;

    canfilter.FilterMode = CAN_FILTERMODE_IDMASK;
    canfilter.FilterScale = CAN_FILTERSCALE_32BIT;

    // filtrate any ID you want here
    canfilter.FilterIdHigh = 0x0000;
    canfilter.FilterIdLow = 0x0000;
    canfilter.FilterMaskIdHigh = 0x0000;
    canfilter.FilterMaskIdLow = 0x0000;

    canfilter.FilterActivation = ENABLE;
    canfilter.SlaveStartFilterBank = 14;

    // use different filter for can1&can2
    if (hcan == &hcan1)
    {
        canfilter.FilterBank = 0;
        canfilter.FilterFIFOAssignment = CAN_FilterFIFO0;
    }
    if (hcan == &hcan2)
    {
        canfilter.FilterBank = 14;
        canfilter.FilterFIFOAssignment = CAN_FilterFIFO1;
    }
    if (HAL_CAN_ConfigFilter(hcan, &canfilter) != HAL_OK)
    {
        Error_Handler();
    }
}

bool board_init() {
    // Initialize all configured peripherals
    MX_GPIO_Init();
    MX_DMA_Init();
    MX_ADC1_Init();
    MX_ADC2_Init();
    MX_ADC3_Init();
    MX_CAN1_Init();
    MX_CAN2_Init();
    MX_I2C1_Init();
    MX_SPI1_Init();
    MX_SPI2_Init();
    MX_UART5_Init();
    MX_USART1_UART_Init();
    MX_USART2_UART_Init();
    MX_USART3_UART_Init();
    MX_USART6_UART_Init();
    MX_TIM2_Init();
    MX_TIM6_Init();
    MX_UART4_Init();
    MX_IWDG_Init();
    MX_TIM1_Init();
    MX_TIM13_Init();
    MX_TIM7_Init();

    HAL_IWDG_Refresh(&hiwdg);

    // Initialize ZCAN for CAN1 and CAN2
    if (!can1_bus.start(&hcan1)) {
        return false;
    }
    if (!can2_bus.start(&hcan2)) {
        return false;
    }
    
    // Subscribe to optical flow sensor (CAN1, ID 0x300)
    MsgIdFilterSpecs optflow_filter;
    optflow_filter.id = (uint16_t)0x300;
    optflow_filter.mask = 0x7FF;  // Match exact ID
    optflow_filter.fifo = CAN_RX_FIFO0;
    can1_bus.subscribe(optflow_filter, on_optflow_rx, nullptr, nullptr);
    
    // Subscribe to motor feedback (CAN2, IDs 0x01-0x205)
    MsgIdFilterSpecs motor_filter;
    motor_filter.id = (uint16_t)0x000;  // Base ID for filtering
    motor_filter.mask = 0x000;  // Match IDs 0x01-0x205
    motor_filter.fifo = CAN_RX_FIFO1;
    can2_bus.subscribe(motor_filter, on_motor_fb_rx, nullptr, nullptr);

    imu.init();
    imu.start_acquisition();

    HAL_TIM_Base_Start_IT(&htim2);

    if (imu.model() == IMU::Model::kIcm42688) {
        HAL_TIM_Base_Start_IT(&htim7);
    }

    // Start TIM13 for optical flow sensor timing
    HAL_TIM_Base_Start(&htim13);

    return true;
}

